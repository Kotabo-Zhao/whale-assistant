"""Build each action's approach from its own illustrated prop/hand choreography.

The neutral end of its return is traversed in reverse, then optical flow settles
the last few drawings onto the action's actual first pose. Both seams are exact.
"""
import argparse
import importlib.util
import bisect
from pathlib import Path
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CELL = 320


def frame(atlas, index):
    left = (index % 4) * CELL
    top = (index // 4) * CELL
    return atlas.crop((left, top, left + CELL, top + CELL))


def travel_distance(frames):
    import numpy as np
    previous = None
    distance = [0]
    for image in frames:
        rgba = np.asarray(image, dtype=np.float32) / 255
        rgba[:, :, :3] *= rgba[:, :, 3:4]
        if previous is not None:
            distance.append(distance[-1] + max(1, round(float(np.abs(previous - rgba).mean()) * 1000)))
        previous = rgba
    return distance


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets', type=Path, default=ROOT / 'android/app/src/main/assets/pet-cels')
    parser.add_argument('--cv-python', type=Path)
    args = parser.parse_args()
    if args.cv_python:
        sys.path.insert(0, str(args.cv_python))
    import cv2
    cv2.setNumThreads(2)
    source = Path(__file__).with_name('interpolate-pet-cels.py')
    spec = importlib.util.spec_from_file_location('pet_interpolation', source)
    interpolation = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(interpolation)
    neutral = frame(Image.open(args.assets / 'idle.webp').convert('RGBA'), 0)
    distances = {}
    for path in sorted(args.assets.glob('*_return.webp')):
        name = path.stem.removesuffix('_return')
        departure = Image.open(path).convert('RGBA')
        first = frame(Image.open(args.assets / f'{name}.webp').convert('RGBA'), 0)
        # Leave enough distinct drawings for picking up the book, pen, cup or phone.
        outgoing = [frame(departure, i) for i in range(31)]
        distances[path.stem] = travel_distance(outgoing)
        approach = outgoing[8:][::-1]
        assert approach[0].tobytes() == neutral.tobytes()
        join = approach[-1]
        for fraction in (.125, .25, .375, .5, .625, .75, .875):
            approach.append(interpolation.interpolate(join, first, fraction)[0])
        approach.append(first)
        # Spend drawing slots on silhouette/pose changes. Several nearly still frames
        # around the neutral pose should not force a standing-to-seated leap later.
        cumulative = travel_distance(approach)
        even = [neutral]
        for i in range(1, 31):
            at = i * cumulative[-1] / 31
            left = bisect.bisect_right(cumulative, at) - 1
            fraction = (at - cumulative[left]) / (cumulative[left + 1] - cumulative[left])
            if fraction < .04:
                even.append(approach[left])
            elif fraction > .96:
                even.append(approach[left + 1])
            else:
                even.append(interpolation.interpolate(approach[left], approach[left + 1], fraction)[0])
        even.append(first)
        sheet = Image.new('RGBA', (CELL * 4, CELL * 8))
        for i, image in enumerate(even):
            sheet.paste(image, ((i % 4) * CELL, (i // 4) * CELL))
        target = args.assets / f'{name}_enter.webp'
        sheet.save(target, 'WEBP', lossless=True, method=6, exact=True)
        decoded = Image.open(target).convert('RGBA')
        assert frame(decoded, 0).tobytes() == neutral.tobytes()
        assert frame(decoded, 31).tobytes() == first.tobytes()
        distances[target.stem] = travel_distance(even)
        print(name, target.stat().st_size, flush=True)
    table = ROOT / 'android/app/src/main/java/io/deepseekharness/mobile/overlay/PetTravelDistance.kt'
    rows = [f'    "{name}" to intArrayOf({", ".join(map(str, values))}),' for name, values in sorted(distances.items())]
    table.write_text('package io.deepseekharness.mobile.overlay\n\n'
                     '// Generated by scripts/prepare-pet-entries.py from premultiplied whole-cel differences.\n'
                     'internal val petTravelDistance = mapOf(\n' + '\n'.join(rows) + '\n)\n', encoding='utf8')


if __name__ == '__main__':
    main()
